import * as Icons from "heroicons-react";
import { signInUser } from "../../Utility/Auth";
import AlertService from "../../Utility/AlertService";
import DatePicker from "react-datepicker";
import { useEffect, useState } from "react";
import { format } from "date-fns";
import WareHouseDW from "../../Common/CustomSelect/WareHouseDW";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { useWarehouseQuery } from "../../../services/warehouseApi";
import SelectUsers from "../../Common/CustomSelect/SelectUsers";
import SelectProduct from "../../Common/CustomSelect/PosSearchProduct";
import SelectProductsReport from "../../Common/CustomSelect/SelectProductsReport";
import { useProductWiseSalesQuery } from "../../../services/reportsApi";

const ProductWiseSales = () => {
  const auth = signInUser();
  // console.log("auth",auth)

  const [warehouse, setWarehouse] = useState("allWh");
  const [productId, setProductId] = useState();

  const [startDate, setStartDate] = useState(format(new Date(), "MM-dd-yyyy"));
  const [endDate, setEndDate] = useState(format(new Date(), "MM-dd-yyyy"));
  const { aamarId } = auth;
  // const lang = useSelector((state) => state.languageReducer);
  const { data: salesData } = useProductWiseSalesQuery({
    startDate,
    endDate,
    warehouse,
    aamarId,
    productId,
  });

  console.log(
    "Product wise Purchase data::>>",
    startDate,
    endDate,
    warehouse,
    aamarId,
    productId
  );

  console.log("purchase data", salesData);

  // fine warehouse Name
  const [whName, setWhName] = useState("All Warehouses");

  const { data: wh, refetch } = useWarehouseQuery(warehouse);

  // Call refetch only if user?.warehouse changes
  useEffect(() => {
    if (warehouse) {
      refetch();
    }
  }, [warehouse, refetch]);

  // Update warehouse name when data changes
  useEffect(() => {
    if (wh?.name) {
      setWhName(wh.name); // Directly set the name, no need for optional chaining here
    }
  }, [wh]);
  // console.log("Customer Wise Sales Report Data:", salesData);

  // Export CSV
  const handleExportCSV = () => {
    if (!salesData || salesData.length === 0) {
      AlertService.alert("Info", "No data available for export.");
      return;
    }

    const start = new Date(startDate).toLocaleDateString("en-US");
    const end = new Date(endDate).toLocaleDateString("en-US");
    const generatedOn = new Date().toLocaleString();
    const generatedBy = auth?.name || "Aamar Dokan";
    const storeName =
      auth?.storeSettings?.storeName?.toUpperCase() || "Aamar Dokan";
    const reportTitle = "Product Wise Purchase Report";

    // Header Info
    const headerInfo = [
      `Store: ${storeName},,,,,,,`,
      `Report: ${reportTitle},,,,,,,Date Range: ${start} to ${end}`,
      `Generated On: ${generatedOn},,,,,,,Generated By: ${generatedBy}`,
      "",
      "",
    ];

    // Table Headers
    const csvTableHeader = [
      "S/N",
      "Invoice No",
      "Warehouse",
      "Date",
      "Biller",
      "Total Items",
      "Discount",
      "Gross Total",
    ].join(",");

    // Totals
    let totalItems = 0;
    let totalDiscount = 0;
    let totalGross = 0;

    // Table Rows
    const csvRows = salesData.map((item, index) => {
      const items = Number(item.totalItem || 0);
      const discount = Number(item.discount || 0);
      const gross = Number(item.grossTotal || 0);

      totalItems += items;
      totalDiscount += discount;
      totalGross += gross;

      return [
        index + 1,
        item.invoiceId || "",
        item.warehouseName || "",
        new Date(item.date).toLocaleDateString("en-US"),
        item.billerName || "",
        items,
        discount.toFixed(2),
        gross.toFixed(2),
      ].join(",");
    });

    // Summary Footer
    const summaryLabelRow = [",,,,,,", "** SUMMARY **"].join(",");
    const summaryHeaderRow = [
      "",
      "",
      "",
      "",
      "",
      "Total Items",
      "Total Discount",
      "Total Gross",
    ].join(",");

    const summaryDataRow = [
      "",
      "",
      "",
      "",
      "",
      totalItems,
      totalDiscount.toFixed(2),
      totalGross.toFixed(2),
    ].join(",");

    // Combine all parts
    const csvContent = [
      ...headerInfo,
      csvTableHeader,
      ...csvRows,
      "",
      "",
      summaryLabelRow,
      summaryHeaderRow,
      summaryDataRow,
    ].join("\n");

    // Export logic
    const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "ProductWiseSales.csv";
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
  };

  // export PDF
  // export PDF for Sales Data
  const handleExportPDF = () => {
    if (!salesData || salesData?.length === 0) {
      AlertService.alert("Info", "No sales data available for export.");
      return;
    }

    const doc = new jsPDF("landscape");

    const options = { month: "numeric", day: "numeric", year: "numeric" };
    const formattedStart = new Date(salesData[0].date).toLocaleDateString("en-US", options);
    const formattedEnd = formattedStart;
    const reportGeneratedAt = new Date().toLocaleString();

    const storeName = auth?.storeSettings?.storeName?.toUpperCase() || "Aamar Dokan";
    const reportName = "Product Wise Sales Report";

    // Title
    doc.setFontSize(16);
    doc.text(storeName, 140, 15, { align: "center" });

    doc.setFontSize(12);
    doc.text(reportName, 140, 22, { align: "center" });

    // Header Info
    doc.setFontSize(10);
    doc.text(`Store: ${storeName}`, 14, 28);
    doc.text(`Date: ${formattedStart} - ${formattedEnd}`, 14, 33);
    doc.text(`Generated At: ${reportGeneratedAt}`, 280, 28, { align: "right" });
    doc.text(`Generated By: ${auth?.name || "System"}`, 280, 33, { align: "right" });

    // Table Headers
    const headers = [[
      "S/N", "Invoice ID", "Date", "Product", "Article Code", "Warehouse",
      "TP", "MRP", "Qty Sold", "Return Qty", "Total Amount", "Profit", "Payment"
    ]];

    const data = salesData.map((item, index) => [
      index + 1,
      item.invoiceId,
      new Date(item.date).toLocaleDateString("en-US"),
      item.productName,
      item.articleCode,
      item.warehouse,
      item.tp.toFixed(2),
      item.mrp.toFixed(2),
      item.quantitySold,
      item.returnQuantity,
      item.totalSalesAmount.toFixed(2),
      item.profit.toFixed(2),
      item.paymentMethod,
    ]);

    autoTable(doc, {
      head: headers,
      body: data,
      startY: 45,
      theme: "grid",
      styles: {
        fontSize: 9,
        halign: "center",
      },
      headStyles: {
        fillColor: [242, 101, 45],
        textColor: [255, 255, 255],
        fontStyle: "bold",
        lineWidth: 0.2,
        lineColor: [255, 255, 255],
      },
    });

    // Summary Box
    const finalY = doc.lastAutoTable.finalY + 10;
    const lineHeight = 6;
    const boxHeight = 5 * lineHeight + 10;
    const boxWidth = 120;

    const pageWidth = doc.internal.pageSize.getWidth();
    const boxX = pageWidth - boxWidth - 15;
    const boxY = finalY;

    doc.setLineDashPattern([1, 1], 0);
    doc.rect(boxX, boxY, boxWidth, boxHeight);
    doc.setLineDashPattern([], 0);

    let y = boxY + 10;
    const labelX = boxX + 5;
    const valueX = boxX + boxWidth - 5;
    doc.setFontSize(9);

    const totalQty = salesData.reduce((sum, item) => sum + item.quantitySold, 0);
    const totalReturnQty = salesData.reduce((sum, item) => sum + item.returnQuantity, 0);
    const totalAmount = salesData.reduce((sum, item) => sum + item.totalSalesAmount, 0);
    const totalProfit = salesData.reduce((sum, item) => sum + item.profit, 0);

    doc.text("Total Quantity Sold :", labelX, y);
    doc.text(`${totalQty}`, valueX, y, { align: "right" });

    y += lineHeight;
    doc.text("Total Return Quantity :", labelX, y);
    doc.text(`${totalReturnQty}`, valueX, y, { align: "right" });

    y += lineHeight;
    doc.text("Total Sales Amount :", labelX, y);
    doc.text(`${totalAmount.toFixed(2)}`, valueX, y, { align: "right" });

    y += lineHeight;
    doc.text("Total Profit :", labelX, y);
    doc.text(`${totalProfit.toFixed(2)}`, valueX, y, { align: "right" });

    doc.save("ProductWiseSales.pdf");
  };


  // Utility to sum values from objects
  const sumField = (data, field) =>
    data
      ?.reduce((acc, item) => acc + (parseFloat(item[field]) || 0), 0)
      .toFixed(2);

  //warehouse
  const handleOnchangeWareHouseFrom = (e) => {
    if (e.option !== "no-warehouse") {
      setWarehouse(e.option);
    } else {
      setWarehouse("allWh");
    }
  };

  return (
    <div>
      <div>
        <h2 className="mb-3">
          <Icons.ShoppingCartOutline size={35} /> Product Wise Sales Report
        </h2>
      </div>

      <div
        className="mt-3 w-40 p-3"
        style={{ backgroundColor: "#f1f3f5", borderRadius: "8px" }}
      >
        <div className="d-flex mt-2 mb-2 align-items-center justify-content-center gap-2">
          <DatePicker
            selected={new Date(startDate)}
            className="form-control w-100"
            onChange={(date) =>
              setStartDate(format(new Date(date), "MM-dd-yyyy"))
            }
          />
          <DatePicker
            selected={new Date(endDate)}
            className="form-control me-4"
            onChange={(date) =>
              setEndDate(format(new Date(date), "MM-dd-yyyy"))
            }
          />
        </div>

        <div className="">
          {auth?.type === "admin" && (
            <div className="my-3">
              <WareHouseDW
                id="warehouse"
                name="warehouse"
                handleOnChange={handleOnchangeWareHouseFrom}
                className="form-control"
              />
            </div>
          )}
          {/* <SelectProductsReport
            onProductSelect={(id) => {
              console.log("Selected Product ID:", id);
              setProductId(id); // Or any custom logic
            }}
          /> */}

          <SelectProductsReport
            onProductSelect={({ id, article_code }) => {
              // console.log("Selected Product ID:", id);
              // console.log("Selected Article Code:", article_code);
              // setProductId(id);
              setProductId(article_code); // Only if you need to store/use it
            }}
          />
        </div>

        <div className="d-flex gap-3 justify-content-center align-items-center text-center">
          <button
            className="btn btn-dark w-100 mt-3"
            style={{ borderRadius: "5px" }}
            onClick={handleExportCSV}
          >
            <Icons.DownloadOutline size={22} /> Download CSV
          </button>

          <button
            className="btn btn-dark w-100 mt-3"
            style={{ borderRadius: "5px" }}
            onClick={handleExportPDF}
          >
            <Icons.DocumentOutline size={22} /> Download PDF
          </button>
        </div>
      </div>
    </div>
  );
};

export default ProductWiseSales;
